import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.ensemble import RandomForestRegressor
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

# ------------------------------------------------------------
# 1. LOAD DATA
# ------------------------------------------------------------

FILE = "WQReport_Wilderness_1971_to_2026.csv"

# The file has two metadata rows before the actual header.
df = pd.read_csv(
    FILE,
    skiprows=2,
    encoding="cp1252"
)

# Remove completely empty columns
df = df.dropna(axis=1, how="all")

# Convert date
df["Date"] = pd.to_datetime(df["Date"])

# Sort chronologically
df = df.sort_values("Date").reset_index(drop=True)

print("Dataset shape:", df.shape)
print("\nDate range:")
print(df["Date"].min(), "to", df["Date"].max())


# ------------------------------------------------------------
# 2. KEEP ONLY OBSERVATIONS WITH CHLOROPHYLL-A
# ------------------------------------------------------------

df = df[df["Chlor-a (µg/L)"].notna()].copy()

df = df.sort_values("Date").reset_index(drop=True)


# ------------------------------------------------------------
# 3. CREATE THE FORECAST TARGET
#
# Target = chlorophyll-a at the NEXT sampling event
#
# Example:
#
# May 1 conditions
#       ↓
# MODEL
#       ↓
# predicted chlorophyll-a on May 15
# ------------------------------------------------------------

df["Next_Chlor_a"] = df["Chlor-a (µg/L)"].shift(-1)

df["Next_Date"] = df["Date"].shift(-1)

df["Days_To_Next_Sample"] = (
    df["Next_Date"] - df["Date"]
).dt.days


# ------------------------------------------------------------
# 4. REMOVE VERY LONG GAPS
#
# We don't want the model pretending that a prediction
# 200 days into the future is comparable to a 14-day forecast.
#
# 30 days is a reasonable initial cutoff for this dataset.
# ------------------------------------------------------------

MAX_FORECAST_GAP = 30

df = df[
    (df["Days_To_Next_Sample"] <= MAX_FORECAST_GAP) &
    (df["Next_Chlor_a"].notna())
].copy()


# ------------------------------------------------------------
# 5. CREATE HISTORICAL/LAG FEATURES
#
# These are extremely important.
#
# The model gets information about what happened previously,
# rather than only looking at today's measurement.
# ------------------------------------------------------------

df["Chlor_a_lag1"] = df["Chlor-a (µg/L)"].shift(1)
df["Chlor_a_lag2"] = df["Chlor-a (µg/L)"].shift(2)
df["Chlor_a_change"] = (
    df["Chlor-a (µg/L)"] -
    df["Chlor_a_lag1"]
)

# Previous temperature
df["Temp_lag1"] = df["Temp (°C)"].shift(1)

# Previous phosphorus
df["TP_lag1"] = df["TP (µg/L)"].shift(1)

# Previous nitrogen
df["TN_lag1"] = df["TN (µg/L)"].shift(1)

# Previous Secchi depth
df["Secchi_lag1"] = df["Secchi (m)"].shift(1)


# ------------------------------------------------------------
# 6. CREATE SEASONAL FEATURES
#
# Algal activity is strongly seasonal.
#
# We represent month as a circular variable so that
# December and January are close to each other.
# ------------------------------------------------------------

df["Month"] = df["Date"].dt.month

df["Month_sin"] = np.sin(
    2 * np.pi * df["Month"] / 12
)

df["Month_cos"] = np.cos(
    2 * np.pi * df["Month"] / 12
)


# ------------------------------------------------------------
# 7. SELECT FEATURES
# ------------------------------------------------------------

features = [
    # Current water quality
    "Secchi (m)",
    "Temp (°C)",
    "Pheo-a (µg/L)",
    "TN (µg/L)",
    "NO2-3 (µg/L)",
    "NH3-N (µg/L)",
    "TP (µg/L)",
    "OPO4 (µg/L)",
    "UV254 (abs.units)",
    "Total Alk (mg/L CaCO3)",

    # Historical chlorophyll
    "Chlor_a_lag1",
    "Chlor_a_lag2",
    "Chlor_a_change",

    # Historical environmental conditions
    "Temp_lag1",
    "TP_lag1",
    "TN_lag1",
    "Secchi_lag1",

    # Time/season
    "Month_sin",
    "Month_cos"
]

target = "Next_Chlor_a"

X = df[features]
y = df[target]


# ------------------------------------------------------------
# 8. CHRONOLOGICAL TRAIN / TEST SPLIT
#
# DO NOT RANDOMLY SHUFFLE.
#
# Earlier observations → training
# Later observations  → testing
# ------------------------------------------------------------

split_index = int(len(df) * 0.80)

X_train = X.iloc[:split_index]
X_test = X.iloc[split_index:]

y_train = y.iloc[:split_index]
y_test = y.iloc[split_index:]

print("\nTraining observations:", len(X_train))
print("Testing observations:", len(X_test))


# ------------------------------------------------------------
# 9. HANDLE MISSING VALUES
# ------------------------------------------------------------

imputer = SimpleImputer(strategy="median")


# ------------------------------------------------------------
# 10. RANDOM FOREST MODEL
# ------------------------------------------------------------

model = RandomForestRegressor(
    n_estimators=500,
    max_depth=8,
    min_samples_leaf=3,
    max_features="sqrt",
    random_state=42,
    n_jobs=-1
)


# ------------------------------------------------------------
# 11. CREATE PIPELINE
# ------------------------------------------------------------

pipeline = Pipeline([
    ("imputer", imputer),
    ("model", model)
])


# ------------------------------------------------------------
# 12. TRAIN
# ------------------------------------------------------------

pipeline.fit(X_train, y_train)


# ------------------------------------------------------------
# 13. PREDICT
# ------------------------------------------------------------

predictions = pipeline.predict(X_test)


# ------------------------------------------------------------
# 14. EVALUATE
# ------------------------------------------------------------

mae = mean_absolute_error(y_test, predictions)

rmse = np.sqrt(
    mean_squared_error(y_test, predictions)
)

r2 = r2_score(y_test, predictions)

print("\n==============================")
print("MODEL PERFORMANCE")
print("==============================")

print(f"MAE  : {mae:.2f} µg/L")
print(f"RMSE : {rmse:.2f} µg/L")
print(f"R²   : {r2:.3f}")


# ------------------------------------------------------------
# 15. CREATE RESULTS TABLE
# ------------------------------------------------------------

results = df.iloc[split_index:].copy()

results["Predicted_Chlor_a"] = predictions

results["Prediction_Error"] = (
    results["Predicted_Chlor_a"] -
    results["Next_Chlor_a"]
)

print("\nSample predictions:")
print(
    results[
        [
            "Date",
            "Next_Date",
            "Days_To_Next_Sample",
            "Next_Chlor_a",
            "Predicted_Chlor_a",
            "Prediction_Error"
        ]
    ].head(15)
)


# ------------------------------------------------------------
# 16. ACTUAL VS PREDICTED GRAPH
# ------------------------------------------------------------

plt.figure(figsize=(10, 6))

plt.scatter(
    y_test,
    predictions,
    alpha=0.7
)

# Perfect prediction line
minimum = min(y_test.min(), predictions.min())
maximum = max(y_test.max(), predictions.max())

plt.plot(
    [minimum, maximum],
    [minimum, maximum],
    linestyle="--"
)

plt.xlabel("Actual Next Chlorophyll-a (µg/L)")
plt.ylabel("Predicted Next Chlorophyll-a (µg/L)")
plt.title("Random Forest: Actual vs Predicted Chlorophyll-a")

plt.tight_layout()
plt.show()


# ------------------------------------------------------------
# 17. TIME-SERIES PREDICTION GRAPH
# ------------------------------------------------------------

plt.figure(figsize=(12, 6))

plt.plot(
    results["Next_Date"],
    results["Next_Chlor_a"],
    label="Actual"
)

plt.plot(
    results["Next_Date"],
    results["Predicted_Chlor_a"],
    label="Predicted"
)

plt.xlabel("Date")
plt.ylabel("Chlorophyll-a (µg/L)")
plt.title("Lake Wilderness Chlorophyll-a Forecast")

plt.legend()

plt.tight_layout()
plt.show()


# ------------------------------------------------------------
# 18. FEATURE IMPORTANCE
# ------------------------------------------------------------

rf = pipeline.named_steps["model"]

importance = pd.DataFrame({
    "Feature": features,
    "Importance": rf.feature_importances_
})

importance = importance.sort_values(
    "Importance",
    ascending=False
)

print("\n==============================")
print("FEATURE IMPORTANCE")
print("==============================")

print(importance)


# ------------------------------------------------------------
# 19. FEATURE IMPORTANCE GRAPH
# ------------------------------------------------------------

plt.figure(figsize=(10, 7))

top_features = importance.head(12)

plt.barh(
    top_features["Feature"][::-1],
    top_features["Importance"][::-1]
)

plt.xlabel("Random Forest Importance")
plt.title("Most Important Water-Quality Predictors")

plt.tight_layout()
plt.show()


# ------------------------------------------------------------
# 20. OPTIONAL: OPERATIONAL ALERT
#
# DO NOT blindly use 2.8 µg/L for Lake Wilderness.
#
# Set this value only after identifying the appropriate
# management threshold for the specific lake/agency.
# ------------------------------------------------------------

ALERT_THRESHOLD = None

if ALERT_THRESHOLD is not None:

    results["Risk"] = np.where(
        results["Predicted_Chlor_a"] >= ALERT_THRESHOLD,
        "ELEVATED",
        "NORMAL"
    )

    print("\nOperational predictions:")
    print(
        results[
            [
                "Next_Date",
                "Predicted_Chlor_a",
                "Risk"
            ]
        ].tail(20)
    )


# ------------------------------------------------------------
# 21. SAVE RESULTS
# ------------------------------------------------------------

results.to_csv(
    "Lake_Wilderness_Chlorophyll_Forecasts.csv",
    index=False
)

importance.to_csv(
    "Lake_Wilderness_Feature_Importance.csv",
    index=False
)

print("\nFiles created:")
print("Lake_Wilderness_Chlorophyll_Forecasts.csv")
print("Lake_Wilderness_Feature_Importance.csv")

